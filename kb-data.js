/* 命中逻辑：优先车系精确/别名，其次品牌，最后兜底 */
export function matchVehicle(brand = '', series = '') {
  const b = String(brand).trim();
  const s = String(series).trim().toLowerCase();
  if (s) {
    const hit = VEHICLE_KB.find(v =>
      v.series.toLowerCase() === s ||
      v.aliases.some(a => s.includes(a.toLowerCase()) || a.toLowerCase().includes(s))
    );
    if (hit) return { ...hit, matched: 'series' };
  }
  if (b) {
    const sameBrand = VEHICLE_KB.filter(v => v.brand === b);
    if (sameBrand.length === 1) return { ...sameBrand[0], matched: 'brand' };
  }
  return { brand: b || '', series: series || '', ...GENERIC_KB, matched: 'generic' };
}
